import csv
import os
import subprocess
import argparse
from rdkit import Chem
from rdkit.Chem import AllChem
import shutil

def optimize_molecule(mol):
    """为分子添加氢原子并进行3D结构嵌入和力场优化"""
    try:
        mol_with_h = Chem.AddHs(mol)
        AllChem.EmbedMolecule(mol_with_h, AllChem.ETKDG())
        AllChem.MMFFOptimizeMolecule(mol_with_h)
        return mol_with_h
    except Exception as e:
        print(f"优化分子时发生错误：{e}")
        return None

def smiles_to_xyz(identifier, smiles, output_dir):
    """将SMILES码转换为.xyz文件并保存到指定目录"""
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        print(f"无法从SMILES码 '{smiles}' 创建分子对象")
        return None
    
    optimized_mol = optimize_molecule(mol)
    if optimized_mol is None:
        return None
    
    # 将分子对象转换为.xyz格式
    xyz_filename = f"{identifier}.xyz"
    xyz_filepath = os.path.join(output_dir, xyz_filename)
    with open(xyz_filepath, 'w') as xyz_file:
        xyz_file.write(f"{len(optimized_mol.GetAtoms())}\n")
        xyz_file.write("Generated by RDKit\n")
        conf = optimized_mol.GetConformer()
        for i, atom in enumerate(optimized_mol.GetAtoms()):
            symbol = atom.GetSymbol()
            pos = conf.GetAtomPosition(i)
            xyz_file.write(f"{symbol} {pos.x:.6f} {pos.y:.6f} {pos.z:.6f}\n")
    
    return xyz_filepath

def run_xtb_optimization(xyz_file, output_dir, charge=0, uhf=0, gfn=2):
    """运行XTB优化计算"""
    # 设置环境变量 - 针对Linux系统优化
    env = os.environ.copy()
    env['OMP_NUM_THREADS'] = str(os.cpu_count() or 4)  # 使用所有可用核心
    env['MKL_NUM_THREADS'] = str(os.cpu_count() or 4)
    env['OMP_STACKSIZE'] = '2G'  # 减少堆栈大小，避免内存问题
    
    # 获取文件名（不包含路径）
    base_name = os.path.splitext(os.path.basename(xyz_file))[0]
    
    # 创建输出子目录
    mol_output_dir = os.path.join(output_dir, base_name)
    os.makedirs(mol_output_dir, exist_ok=True)
    
    # 复制而不是移动XYZ文件到子目录
    new_xyz_path = os.path.join(mol_output_dir, f"{base_name}.xyz")
    
    # 使用复制而不是移动，避免权限问题
    try:
        shutil.copy2(xyz_file, new_xyz_path)
    except Exception as e:
        print(f"复制文件失败: {e}")
        return None
    
    # 运行XTB优化
    try:
        # 使用绝对路径确保XTB能找到文件
        abs_xyz_path = os.path.abspath(new_xyz_path)
        
        # 构建XTB命令
        cmd = [
            'xtb', abs_xyz_path, 
            '--chrg', str(charge), 
            '--uhf', str(uhf), 
            '--gfn', str(gfn), 
            '--opt'
        ]
        
        print(f"运行命令: {' '.join(cmd)}")
        print(f"工作目录: {os.path.abspath(mol_output_dir)}")
        
        # 在Linux上运行XTB
        result = subprocess.run(
            cmd,
            cwd=mol_output_dir,
            capture_output=True,
            text=True,
            env=env
        )
        
        # 保存输出
        output_file = os.path.join(mol_output_dir, f"{base_name}_xtb.out")
        with open(output_file, 'w') as f:
            f.write("STDOUT:\n")
            f.write(result.stdout)
            if result.stderr:
                f.write("\n\nSTDERR:\n")
                f.write(result.stderr)
        
        print(f"XTB返回码: {result.returncode}")
        
        # 检查XTB是否成功运行
        if result.returncode != 0:
            print(f"XTB优化失败: {base_name}")
            if result.stderr:
                print(f"错误输出: {result.stderr[:500]}...")  # 只显示前500个字符
            return None
        
        # 检查是否生成了优化后的结构文件
        opt_xyz_path = os.path.join(mol_output_dir, "xtbopt.xyz")
        if not os.path.exists(opt_xyz_path):
            print(f"XTB优化未生成预期输出文件: {opt_xyz_path}")
            return None
            
        return mol_output_dir
    except Exception as e:
        print(f"运行XTB时发生错误: {e}")
        import traceback
        traceback.print_exc()
        return None

def create_gaussian_input(xtb_output_dir, gjf_output_dir):
    """为XTB优化后的分子创建Gaussian输入文件"""
    # 获取分子标识符（目录名）
    identifier = os.path.basename(xtb_output_dir)
    
    # 检查是否存在优化后的结构
    opt_xyz_path = os.path.join(xtb_output_dir, "xtbopt.xyz")
    if not os.path.exists(opt_xyz_path):
        print(f"未找到优化后的结构: {identifier}")
        return None
    
    # 读取优化后的XYZ文件
    with open(opt_xyz_path, 'r') as f:
        lines = f.readlines()
    
    # 获取原子数
    num_atoms = int(lines[0].strip())
    
    # 创建Gaussian输入文件
    gjf_filename = f"{identifier}.gjf"
    gjf_path = os.path.join(gjf_output_dir, gjf_filename)
    
    with open(gjf_path, 'w') as gaussian_file:
        # 写入Gaussian输入文件头
        gaussian_file.write("%%mem=200GB\n%%nprocshared=64\n%%chk=%s.chk\n#p B3LYP/def2svp Opt \n\n" % identifier)
        gaussian_file.write("%s\n\n" % identifier)
        gaussian_file.write("0 1\n")
        
        # 写入原子坐标
        for i in range(2, 2 + num_atoms):
            atom_info = lines[i].split()
            element = atom_info[0]
            x, y, z = map(float, atom_info[1:4])
            gaussian_file.write("%s    %.5f    %.5f    %.5f\n" % (element, x, y, z))
        
        gaussian_file.write("\n\n\n")
    
    return gjf_path

def process_single_smiles(smiles, identifier, xyz_dir, xtb_dir, gjf_dir, charge=0, uhf=0, gfn=2):
    """处理单个SMILES字符串"""
    print(f"处理分子: {identifier}")
    
    # 创建XYZ文件
    xyz_path = smiles_to_xyz(identifier, smiles, xyz_dir)
    if not xyz_path:
        print(f"创建XYZ文件失败: {identifier}")
        return False
    
    # 运行XTB优化
    xtb_output_dir = run_xtb_optimization(xyz_path, xtb_dir, charge, uhf, gfn)
    if not xtb_output_dir:
        print(f"XTB优化失败: {identifier}")
        return False
    
    # 创建Gaussian输入文件
    gjf_path = create_gaussian_input(xtb_output_dir, gjf_dir)
    if not gjf_path:
        print(f"创建Gaussian输入文件失败: {identifier}")
        return False
    
    print(f"成功处理: {identifier}")
    return True

def process_csv_file(csv_file, xyz_dir, xtb_dir, gjf_dir, id_col=0, smiles_col=1, charge=0, uhf=0, gfn=2):
    """处理CSV文件中的多个SMILES字符串"""
    success_count = 0
    total_count = 0
    
    with open(csv_file, 'r') as file:
        reader = csv.reader(file)
        next(reader)  # 跳过标题行
        
        for row in reader:
            total_count += 1
            identifier = row[id_col]
            smiles = row[smiles_col]
            
            if process_single_smiles(smiles, identifier, xyz_dir, xtb_dir, gjf_dir, charge, uhf, gfn):
                success_count += 1
    
    print(f"处理完成: {success_count}/{total_count} 个分子成功")

def main():
    parser = argparse.ArgumentParser(description="从SMILES码生成XTB优化结构和Gaussian输入文件")
    
    # 输入选项
    input_group = parser.add_mutually_exclusive_group(required=True)
    input_group.add_argument('--smiles', type=str, help='直接输入SMILES码')
    input_group.add_argument('--csv', type=str, help='包含SMILES码的CSV文件路径')
    
    # 标识符选项
    parser.add_argument('--identifier', type=str, default='molecule', help='分子标识符（当使用--smiles时）')
    
    # 目录选项
    parser.add_argument('--xyz-dir', type=str, default='./xyz_files', help='XYZ文件输出目录')
    parser.add_argument('--xtb-dir', type=str, default='./xtb_output', help='XTB输出目录')
    parser.add_argument('--gjf-dir', type=str, default='./gaussian_inputs', help='Gaussian输入文件输出目录')
    
    # CSV文件列选项
    parser.add_argument('--id-col', type=int, default=0, help='CSV文件中标识符列的索引（从0开始）')
    parser.add_argument('--smiles-col', type=int, default=1, help='CSV文件中SMILES码列的索引（从0开始）')
    
    # XTB计算选项
    parser.add_argument('--charge', type=int, default=0, help='分子电荷')
    parser.add_argument('--uhf', type=int, default=0, help='未配对电子数')
    parser.add_argument('--gfn', type=int, default=2, help='GFN方法（1, 2或FF）')
    
    args = parser.parse_args()
    
    # 创建输出目录
    os.makedirs(args.xyz_dir, exist_ok=True)
    os.makedirs(args.xtb_dir, exist_ok=True)
    os.makedirs(args.gjf_dir, exist_ok=True)
    
    # 处理输入
    if args.smiles:
        process_single_smiles(
            args.smiles, 
            args.identifier, 
            args.xyz_dir, 
            args.xtb_dir, 
            args.gjf_dir,
            args.charge,
            args.uhf,
            args.gfn
        )
    elif args.csv:
        process_csv_file(
            args.csv, 
            args.xyz_dir, 
            args.xtb_dir, 
            args.gjf_dir,
            args.id_col,
            args.smiles_col,
            args.charge,
            args.uhf,
            args.gfn
        )

if __name__ == "__main__":
    main()